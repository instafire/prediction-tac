import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
mkdirSync("screenshots/zoom", { recursive: true });
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1000, height: 900 }, deviceScaleFactor: 2 });
const page = await ctx.newPage();
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
await page.goto("http://127.0.0.1:8791/", { waitUntil: "domcontentloaded", timeout: 30000 });
await page.evaluate(() => localStorage.setItem("ptac-prefs", JSON.stringify({ onboardingDone: true, haptics: false, sounds: false, reduceMotion: true, endingAlerts: false, alertThresholdHrs: 24 })));
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
await page.locator(".nav-tabs button", { hasText: "Markets" }).first().click().catch(() => {});
await page.waitForTimeout(900);
await page.locator(".grid .card .card-head", { hasText: "all-time-high" }).first().click().catch(() => {});
await page.waitForTimeout(1200);
await page.locator(".grid .card.exp .chart-wrap").first().screenshot({ path: "screenshots/zoom/final.png" });
console.log("errors=" + errs.length);
await browser.close();
console.log("DONE");
